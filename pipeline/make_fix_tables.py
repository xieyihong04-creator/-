DATA = {
    'shang': (SHANG_FIX, SHANG_QUERY),
    'xia': (XIA_FIX, XIA_QUERY),
}


def anchor(sec):
    return f'{int(round(sec))}s'


def build(ep):
    fix, query = DATA[ep]
    subs_p = os.path.join(paths.OUT, f'{ep}.zh.final.json')
    lines = B.zh_lines(B.load(subs_p))          # pre-fix text, drops applied
    table = []
    for i in sorted(fix):
        v = fix[i]
        if not (0 <= i < len(lines)):
            raise SystemExit(f'{ep}: index {i} out of range ({len(lines)} lines)')
        e = {'i': i, 'expect': lines[i]['t'], 'at': anchor(lines[i]['s']), 'text': v or ''}
        if v is None:
            e['drop'] = True
            e['note'] = '與相鄰完整句重複的 OCR 殘句，或燒錄在畫面上的非字幕文字'
        else:
            r = difflib.SequenceMatcher(None, e['expect'], e['text']).ratio()
            if r < MIN_RATIO and i not in query:
                print(f'  note {ep} line {i}: large rewrite (ratio {r:.2f})')
            if i in query:
                e['query'] = True
                e['note'] = '字幕被裁切，依英文旁白推定，建議比對影片'
        table.append(e)
    table.sort(key=lambda e: e['i'])
    out_p = B.fix_table_for(subs_p)
    with open(out_p, 'w', encoding='utf-8') as f:
        json.dump(table, f, ensure_ascii=False, indent=1)
    print(f'{os.path.basename(out_p)}: entries={len(table)} '
          f'drops={sum(1 for e in table if e.get("drop"))} '
          f'queries={sum(1 for e in table if e.get("query"))}')


if __name__ == '__main__':
    for ep in sys.argv[1:] or ['shang', 'xia']:
        build(ep)
